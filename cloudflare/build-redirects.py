#!/usr/bin/env python3
"""Generate Cloudflare _redirects from vercel.json.

Run from the repository root: python3 cloudflare/build-redirects.py
Re-run whenever routes change in vercel.json, then commit _redirects.
"""
import json

d = json.load(open("vercel.json"))
static, rewrites, slashless = [], [], []

def add_slashless(src, dest, code):
    # Vercel trailingSlash: true sends /x to /x/. Recreate that explicitly.
    if src.endswith("/") and src != "/":
        slashless.append(f"{src.rstrip('/')} {dest} {code}")

for r in d["redirects"]:
    if "has" in r:
        continue  # host-conditional rule, handled in cloudflare/worker.js
    code = 308 if r["permanent"] else 307
    static.append(f"{r['source']} {r['destination']} {code}")
    add_slashless(r["source"], r["destination"], code)

for r in d["rewrites"]:
    rewrites.append(f"{r['source']} {r['destination']} 200")
    add_slashless(r["source"], r["source"], 308)

lines = ["# Generated by cloudflare/build-redirects.py from vercel.json. Do not edit by hand.",
         "", "# Permanent and temporary redirects"] + static + \
        ["", "# Trailing-slash normalisation"] + slashless + \
        ["", "# Clean URL to HTML file mappings"] + rewrites
open("_redirects", "w").write("\n".join(lines) + "\n")
print(len(static), "redirects,", len(slashless), "slash redirects,", len(rewrites), "rewrites")
